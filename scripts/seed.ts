/**
 * Demo seed (T054, FR-039): builds the demo state on the REAL local ELEVATE and in the programme
 * stores of one profile. Idempotent: ELEVATE ids are kept in `infra/compose/.seed-state.<p>.json`
 * and programme documents are upserted, so a re-run creates nothing new.
 *
 *   npm run seed -- --profile test [--mongo-url mongodb://127.0.0.1:27027/?directConnection=true]
 *
 * Prints a summary (role, name, login, scope; never passwords) and writes docs/demo-users.md.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import mongoose from 'mongoose';
import { ALL_WARDS, ASSESSORS, CYCLES, PEOPLE, serviceSlug, WARD4_KEY } from './lib/demo-data.js';
import { ElevateSeeder } from './lib/seed-elevate.js';
import {
  loadState, parseArgs, ProfileEnv, programmeMongoUrl, ROOT, type SeedArgs,
} from './lib/seed-env.js';
import { ProgrammeSeeder } from './lib/seed-programme.js';

const ROLE_LABEL: Record<string, string> = {
  STATE_ADMIN: 'State administrator', DISTRICT_QM: 'District quality manager', IPC_OFFICER: 'IPC officer',
  WARD_SUPERVISOR: 'Ward supervisor', FRONTLINE: 'Frontline staff', MENTOR: 'Expert mentor', EXTERNAL_AUDITOR: 'External auditor',
};

export async function runSeed(args: SeedArgs): Promise<{ elevateCreated: number; programmeWrites: number }> {
  const started = Date.now();
  const env = new ProfileEnv(args.profile);
  const log = (s: string) => console.log(env.redact(s));
  const state = loadState(args.profile);
  const mongoUrl = programmeMongoUrl(args, env);
  log(`seed — profile ${args.profile} — generation ${state.generation}`);

  const elevate = new ElevateSeeder(env, state, log);
  let er;
  try {
    er = await elevate.run();
  } finally {
    await elevate.close();
  }
  const programme = new ProgrammeSeeder(args.profile, state, er.prefix, log);
  let pr;
  try {
    pr = await programme.run(mongoUrl);
  } finally {
    await mongoose.disconnect().catch(() => undefined);
  }

  // ---- summary ----------------------------------------------------------------------------------
  const rows = PEOPLE.map((p) => [ROLE_LABEL[p.role]!, er.users[p.slug]!.name, er.users[p.slug]!.email, pr.scopes[p.slug]!]);
  for (const w of ALL_WARDS) {
    const u = er.users[serviceSlug(w.key)]!;
    rows.push(['Ward service account (FR-018a)', u.name, u.email, `${w.hospital.name} ${w.name} (owns the ward plan in ELEVATE)`]);
  }
  const c1 = CYCLES.find((c) => c.status === 'active')!.code;
  const w4 = pr.ward4;
  const ward4Rows: [string, string][] = [
    ['Ward code (ELEVATE externalId)', w4.wardCode],
    ['Programme ward id', w4.wardId],
    ['Programme facility id (Hospital A)', w4.facilityId],
    ['ELEVATE ward entity id', w4.elevateEntityId],
    ['Ward service account user id', w4.serviceAccountUserId],
    [`ELEVATE observation, officer-a, ${c1}`, state.observations[`${c1}:officer-a`] ?? ''],
    [`ELEVATE submission, officer-a, ${c1}`, state.submissions[`${c1}:officer-a:${WARD4_KEY}`] ?? ''],
    [`ELEVATE submission, auditor, ${c1}`, state.submissions[`${c1}:auditor:${WARD4_KEY}`] ?? ''],
    [`ELEVATE checklist v1 solution (${c1} observations)`, state.checklist?._id ?? ''],
    [`ELEVATE plan solution ${c1} / template copy`, `${state.cycles[c1]?.planSolutionId ?? ''} / ${state.cycles[c1]?.planTemplateCopyId ?? ''}`],
  ];
  const table = (head: string[], body: string[][]) => [
    `| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...body.map((r) => `| ${r.map((c) => c.replace(/\|/g, '\\|')).join(' | ')} |`),
  ].join('\n');

  log('\nDemo users (password: DEMO_USER_PASSWORD in the profile env file)');
  for (const r of rows) log(`  ${r[0]!.padEnd(31)} ${r[1]!.padEnd(42)} ${r[2]!.padEnd(42)} ${r[3]}`);
  log('\nWard 4 (Hospital A, District 1)');
  for (const [k, v] of ward4Rows) log(`  ${k.padEnd(48)} ${v}`);

  const assessorLines = ASSESSORS.map((a) => `- ${er.users[a.slug]!.name} (${a.type}): one observation per cycle solution covering ${a.wards.length} wards`);
  const doc = [
    '# Demo users',
    '',
    `Generated by \`npm run seed -- --profile ${args.profile}\` (generation ${state.generation}) on ${new Date().toISOString()}.`,
    'All demo accounts share the password in `DEMO_USER_PASSWORD` of the git-ignored `infra/compose/.env.<profile>`; no secret is written here.',
    'Users live in the ELEVATE organisation `default_code` (the org admin and checklist recipe of research E18/E19); profile separation is by the code prefix on emails, entities and solutions.',
    '',
    table(['Role', 'Display name', 'Login identifier', 'Scope'], rows),
    '',
    '## Assessors and observations (research E6)',
    '',
    ...assessorLines,
    '',
    '## Ward 4',
    '',
    table(['Item', 'Id'], ward4Rows),
    '',
    '## Back-dated data (US7, US8)',
    '',
    '- Cycle 2026-C0 (closed) has completed baselines for Hospital A Ward 4 (fails the critical "hand-rub at bed" question) and Ward 1, completed in ELEVATE and dated September 2026 in the programme.',
    '- Ward 4 baseline evidence: one photo without GPS and one with a 31-minute device clock skew (Edge metadata only; no MinIO object).',
    '',
  ].join('\n');
  writeFileSync(join(ROOT, 'docs/demo-users.md'), env.redact(doc));

  const secs = ((Date.now() - started) / 1000).toFixed(1);
  log(`\nELEVATE objects created this run: ${er.created}; programme writes: ${pr.writes} (ledger records: ${pr.ledgerRecords}); ${secs} s`);
  log('wrote docs/demo-users.md');
  return { elevateCreated: er.created, programmeWrites: pr.writes };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  try {
    await runSeed(parseArgs());
    process.exit(0);
  } catch (e) {
    const env = (() => { try { return new ProfileEnv(parseArgs().profile); } catch { return undefined; } })();
    const m = e instanceof Error ? `${e.message}${e.stack ? `\n${e.stack.split('\n').slice(1, 4).join('\n')}` : ''}` : String(e);
    console.error(`seed failed: ${env ? env.redact(m) : m.replace(/eyJ[\w-]+\.[\w-]+\.[\w-]+/g, '[jwt]')}`);
    process.exit(1);
  }
}
